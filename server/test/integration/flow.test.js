const { test } = require('node:test');
const assert = require('node:assert/strict');
const { startIntegration, intake, planFor, book, start, clock, day, future, mealSlotAt } = require('../../test-support/integration');

test('real MongoDB + HTTP flow across Manager, Trainer, Vet, Groom and Owner', { skip: !process.env.TEST_MONGO_URI }, async (t) => {
  const ctx = await startIntegration('flow');
  t.after(() => ctx.close());
  const { api, raw, users, models } = ctx;
  let horse, record, plan, race, feed;
  await t.test('A: intake, care assignment, ration, meal, exam and race', async () => {
    ({ horse, record } = await intake(ctx));
    const checklist = await api('trainer', 'GET', `/horses/${horse._id}/checklist`);
    assert.ok(checklist.items.find((i) => i.key === 'health').done);
    feed = await api('manager', 'POST', '/inventory', { name: 'TEST hay', category: 'feed', unit: 'kg', quantity: 100 }, 201);
    await api('trainer', 'POST', '/feeding', { horse: horse._id, mealTime: mealSlotAt(), timeOfDay: clock(), items: [{ inventoryItem: feed._id, amount: 2 }] }, 201);
    await api('trainer', 'POST', '/feeding', { horse: horse._id, mealTime: mealSlotAt(), timeOfDay: clock(), items: [{ inventoryItem: feed._id, amount: 1 }] }, 409);
    const tasks = await api('groom', 'GET', `/stable/tasks?horse=${horse._id}`);
    const meal = tasks.find((task) => task.taskType === 'feeding');
    assert.ok(meal, 'Ration should generate a meal task');
    const op = { clientOpId: 'flow-meal-1', performedAt: new Date().toISOString() };
    await api('groom', 'PATCH', `/stable/tasks/${meal._id}/complete`, op);
    await api('groom', 'PATCH', `/stable/tasks/${meal._id}/complete`, op);
    assert.equal((await models.InventoryItem.findById(feed._id)).quantity, 98);
    race = await api('trainer', 'POST', '/races', { horse: horse._id, raceName: 'TEST Future Cup', raceDate: day(14).toISOString(), distance: 1600, venue: 'Test course', surface: 'dirt' }, 201);
    assert.equal(race.status, 'registered');
    await api('outsider', 'GET', `/horses/${horse._id}`, undefined, 403);
    await api('groom', 'POST', '/races', { horse: horse._id }, 403);
    const requests = await api('trainer', 'POST', '/health/exam-requests', { horse: horse._id, reason: 'Test request' }, 201);
    await api('vet', 'POST', '/health/records', { horse: horse._id, diagnosis: 'Follow-up test', resultStatus: 'eligible', clearedLevel: 'high' }, 201);
    assert.equal((await models.ExamRequest.findById(requests._id)).status, 'done');
  });
  await t.test('A: active plan, weekly generation, no duplicate sessions', async () => {
    plan = await planFor(ctx, horse, { phases: [{ key: 'base_building', weeks: 3, distanceTarget: 1600, weeklyVolumeKm: 20, intensity: 'moderate', surface: 'dirt', week: [{ day: day(1).getDay(), kind: 'walk' }] }] });
    assert.equal(await models.TrainingSession.countDocuments({ trainingPlan: plan._id }), 0);
    await api('trainer', 'POST', '/training/plans', { horse: horse._id, phase: 'base_building', distanceTarget: 1600, weeklyVolumeKm: 20, surface: 'dirt', startDate: day().toISOString(), status: 'active' }, 409);
    await api('trainer', 'POST', `/training/plans/${plan._id}/generate-week`, { weekStart: day(1).toISOString() }, 201);
    const count = await models.TrainingSession.countDocuments({ trainingPlan: plan._id });
    assert.ok(count > 0);
    await api('trainer', 'POST', `/training/plans/${plan._id}/generate-week`, { weekStart: day(1).toISOString() }, 201);
    assert.equal(await models.TrainingSession.countDocuments({ trainingPlan: plan._id }), count);
  });
  await t.test('B: pre-check, start, concurrent end, evaluation and post-work care', async () => {
    const session = await book(ctx, horse, plan, { kind: 'breeze' });
    await start(ctx, session);
    const results = await Promise.all([raw('trainer', 'POST', `/training/sessions/${session._id}/end`, { metrics: { distance: 1600, maxSpeed: 60, avgHeartRate: 170 } }), raw('trainer', 'POST', `/training/sessions/${session._id}/end`, {})]);
    assert.deepEqual(results.map((r) => r.status).sort(), [200, 409]);
    const finished = await models.TrainingSession.findById(session._id);
    assert.equal(finished.status, 'completed');
    assert.ok(finished.actualEndAt >= finished.actualStartAt);
    assert.equal(await models.DailyTask.countDocuments({ trainingSession: session._id }), 2);
    await api('trainer', 'PATCH', `/training/sessions/${session._id}/evaluation`, { performanceRating: 8, trainerComment: 'Test complete', videoUrl: 'https://example.com/test-video' });
    await api('trainer', 'PATCH', `/training/sessions/${session._id}/evaluation`, { performanceRating: 9 });
    assert.equal((await models.TrainingSession.findById(session._id)).status, 'evaluated');
    assert.equal(await models.AuditLog.countDocuments({ targetId: session._id, action: 'trainingSession.evaluation_corrected' }), 1);
  });
  await t.test('C: linked trial and decision; health changes flag review', async () => {
    const trial = await book(ctx, horse, plan, { kind: 'trial', raceEntry: race._id, scheduledAt: future(12) });
    assert.equal(String(trial.raceEntry), race._id);
    await start(ctx, trial);
    await api('trainer', 'POST', `/training/sessions/${trial._id}/end`, { metrics: { distance: 1600, maxSpeed: 65, avgHeartRate: 170 } });
    await api('trainer', 'POST', `/races/${race._id}/decision`, { decision: 'confirmed', trialSession: trial._id, reason: 'Test decision with trial evidence' });
    await api('vet', 'POST', '/health/records', { horse: horse._id, diagnosis: 'Test monitoring', resultStatus: 'monitoring', clearedLevel: 'moderate' }, 201);
    assert.equal((await models.RaceEntry.findById(race._id)).reviewNeeded, true);
    await api('trainer', 'POST', `/races/${race._id}/decision`, { decision: 'withdrawn', reason: 'Test withdrawal for health' });
    await api('trainer', 'PATCH', `/races/${race._id}/results`, { position: 1 }, 409);
    await api('vet', 'POST', '/health/records', { horse: horse._id, diagnosis: 'Test cleared', resultStatus: 'eligible', clearedLevel: 'high' }, 201);
  });
  await t.test('C: race-day result, prize correction and owner/manager reports', async () => {
    const todayRace = await api('trainer', 'POST', '/races', { horse: horse._id, raceName: 'TEST Today Cup', raceDate: day().toISOString(), distance: 1600 }, 201);
    await api('trainer', 'PATCH', `/races/${todayRace._id}/results`, { position: 1, finishTime: '1:40', prizeMoney: 1000000 });
    const entry = await models.RaceEntry.findById(todayRace._id);
    const prizeId = String(entry.financeRecord);
    await api('manager', 'PUT', `/finance/${prizeId}`, { amount: 2 }, 409);
    await api('manager', 'DELETE', `/finance/${prizeId}`, undefined, 409);
    await api('trainer', 'PATCH', `/races/${todayRace._id}/results`, { prizeMoney: 1200000 });
    assert.equal((await models.FinancialRecord.findById(prizeId)).amount, 1200000);
    assert.equal(await models.FinancialRecord.countDocuments({ horse: horse._id, source: 'race_prize' }), 1);
    const summary = await api('owner', 'GET', '/finance/mine/summary');
    assert.equal(summary.totals.revenue, 1200000);
    assert.ok((await api('owner', 'GET', '/horses/owner-summary')).length > 0);
    assert.ok(await api('manager', 'GET', '/reports/overview'));
    const csv = await raw('manager', 'GET', '/export/finance');
    assert.equal(csv.status, 200);
    assert.match(csv.body, /1200000/);
  });
  await t.test('D: approval leaves stock unchanged; concurrent receive counts once', async () => {
    const requested = await api('groom', 'POST', `/inventory/${feed._id}/restock-request`, { quantity: 10, note: 'Test restock' });
    const request = requested.restockRequests.at(-1);
    const before = (await models.InventoryItem.findById(feed._id)).quantity;
    await api('manager', 'PATCH', `/inventory/${feed._id}/restock-requests/${request._id}`, { status: 'approved' });
    assert.equal((await models.InventoryItem.findById(feed._id)).quantity, before);
    const received = await Promise.all([raw('manager', 'POST', `/inventory/${feed._id}/receive`, { requestId: request._id }), raw('manager', 'POST', `/inventory/${feed._id}/receive`, { requestId: request._id })]);
    assert.deepEqual(received.map((r) => r.status).sort(), [200, 409]);
    assert.equal((await models.InventoryItem.findById(feed._id)).quantity, before + 10);
  });
  await t.test('D: delayed care sync retains performedAt, retries once and rejects expired metadata', async () => {
    const performedAt = new Date(Date.now() - 20 * 60000).toISOString();
    const task = await models.DailyTask.create({ horse: horse._id, assignedTo: users.groom.id, taskType: 'cleaning', scheduledDate: day(), supplies: [{ inventoryItem: feed._id, amount: 1 }] });
    const payload = { performedAt, clientOpId: 'offline-care-1' };
    await api('groom', 'PATCH', `/stable/tasks/${task._id}/complete`, payload);
    await api('groom', 'PATCH', `/stable/tasks/${task._id}/complete`, payload);
    const done = await models.DailyTask.findById(task._id);
    assert.equal(done.completedAt.toISOString(), performedAt);
    assert.equal(done.recordedLate, true);
    assert.ok(done.receivedAt > done.completedAt);
    await api('groom', 'PATCH', `/stable/tasks/${task._id}/complete`, { performedAt: new Date(Date.now() - 25 * 3600000).toISOString() }, 409);
  });
  await t.test('E: fever, abort, return assessment and archive preserve history', async () => {
    const fixture = await intake(ctx, 'TEST Recovery');
    const recoveryPlan = await planFor(ctx, fixture.horse);
    const fever = await book(ctx, fixture.horse, recoveryPlan);
    await api('trainer', 'POST', `/training/sessions/${fever._id}/pre-check`, { confirmed: true, bodyTempC: 39 }, 409);
    assert.equal((await models.TrainingSession.findById(fever._id)).status, 'blocked');
    assert.equal(await models.ExamRequest.countDocuments({ horse: fixture.horse._id, status: 'pending' }), 1);
    await api('vet', 'POST', '/health/records', { horse: fixture.horse._id, diagnosis: 'Fever resolved', resultStatus: 'eligible', clearedLevel: 'high' }, 201);
    const run = await book(ctx, fixture.horse, recoveryPlan, { kind: 'walk' });
    await start(ctx, run);
    const treatment = await api('vet', 'POST', '/health/treatments', { horse: fixture.horse._id, healthRecord: fixture.record._id, trainingLevel: 'none', lockReason: 'Test medical lock' }, 201);
    assert.equal((await models.TrainingSession.findById(run._id)).status, 'aborted');
    await api('vet', 'PUT', `/health/treatments/${treatment._id}`, { status: 'completed' });
    const { getTrainingClearance } = require('../../src/modules/health/trainingClearance');
    assert.equal((await getTrainingClearance(fixture.horse._id)).level, 'none');
    await api('vet', 'POST', '/health/records', { horse: fixture.horse._id, diagnosis: 'Return to work', resultStatus: 'eligible', clearedLevel: 'high' }, 201);
    assert.equal((await getTrainingClearance(fixture.horse._id)).level, 'high');
    await api('manager', 'PATCH', `/horses/${fixture.horse._id}/archive`, { reason: 'End test' });
    assert.equal((await models.Horse.findById(fixture.horse._id)).isArchived, true);
    await api('trainer', 'GET', `/horses/${fixture.horse._id}`, undefined, 403);
    assert.ok(await api('owner', 'GET', `/horses/${fixture.horse._id}`));
  });
  await t.test('F: a groom sees the sessions of their own horses only; from/to on the booked time', async () => {
    const otherGroom = await models.User.create({ name: 'TEST other groom', email: 'other-groom@integration.test', passwordHash: 'not-used', role: 'groom' });
    const theirHorse = await api('manager', 'POST', '/horses', { name: 'TEST Other Stall', breed: 'Thoroughbred', owner: users.owner.id, assignedTrainer: users.trainer.id, assignedVet: users.vet.id }, 201);
    await api('manager', 'POST', '/stable/assignments', { horse: theirHorse._id, stableBlock: 'TEST Block B', assignedCaretaker: String(otherGroom._id) }, 201);
    await api('vet', 'POST', '/health/records', { horse: theirHorse._id, diagnosis: 'Test assessment', resultStatus: 'eligible', clearedLevel: 'high' }, 201);
    const theirs = await book(ctx, theirHorse, await planFor(ctx, theirHorse));
    const mine = await book(ctx, horse, plan, { scheduledAt: future(30) });
    const list = await api('groom', 'GET', '/training/sessions');
    assert.ok(list.length > 0 && list.every((s) => String(s.horse._id) === String(horse._id)), 'only the horses this groom looks after');
    assert.deepEqual(await api('groom', 'GET', `/training/sessions?horse=${theirHorse._id}`), []);
    await api('groom', 'GET', `/training/sessions/${theirs._id}`, undefined, 403);
    assert.equal((await api('groom', 'GET', `/training/sessions/${mine._id}`))._id, mine._id);
    assert.ok((await api('trainer', 'GET', '/training/sessions')).some((s) => s._id === theirs._id), 'the trainer still sees both horses');
    const from = encodeURIComponent(new Date(Date.now() + 25 * 60000).toISOString());
    const to = encodeURIComponent(new Date(Date.now() + 35 * 60000).toISOString());
    assert.deepEqual((await api('groom', 'GET', `/training/sessions?from=${from}&to=${to}`)).map((s) => s._id), [mine._id]);
    await api('groom', 'GET', '/training/sessions?from=not-a-date', undefined, 400);
    await api('groom', 'GET', `/training/sessions?from=${to}&to=${from}`, undefined, 400);
  });
});
